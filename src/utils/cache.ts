import { parse, stringify } from "yaml";

import { exists, readText, writeText } from "./fs.ts";

// ---------------------------------------------------------------------------
// The on-disk cache of already downloaded app bundles.
//
// artcraft-apps/dist/versions.yaml remembers which version of every app is
// currently stored in artcraft-apps/dist/<folder>/, so a scheduled run can tell
// whether anything has to be downloaded again.
// ---------------------------------------------------------------------------

/** One cached app entry, as written to versions.yaml. */
export interface CachedApp {
	version: string;
	tag: string;
	artifact: string;
	published_at: string;
	cached_at: string;
}

/** The whole versions.yaml file. */
export interface VersionCache {
	updated_at: string;
	apps: Record<string, CachedApp>;
}

export function emptyVersionCache(): VersionCache {
	return { updated_at: new Date(0).toISOString(), apps: {} };
}

/** Reads versions.yaml; a missing or broken file yields an empty cache. */
export async function readVersionCache(path: string): Promise<VersionCache> {
	if (!(await exists(path))) return emptyVersionCache();
	try {
		const parsed = parse(await readText(path)) as Partial<VersionCache> | null;
		if (parsed === null || typeof parsed !== "object") return emptyVersionCache();
		const apps: Record<string, CachedApp> = {};
		for (const [folder, value] of Object.entries(parsed.apps ?? {})) {
			const entry = value as Partial<CachedApp> | undefined;
			if (entry === undefined || entry === null || typeof entry.version !== "string") continue;
			apps[folder] = {
				version: entry.version,
				tag: typeof entry.tag === "string" ? entry.tag : `v${entry.version}`,
				artifact: typeof entry.artifact === "string" ? entry.artifact : "",
				published_at: typeof entry.published_at === "string" ? entry.published_at : "",
				cached_at: typeof entry.cached_at === "string" ? entry.cached_at : "",
			};
		}
		return {
			updated_at: typeof parsed.updated_at === "string" ? parsed.updated_at : new Date(0).toISOString(),
			apps,
		};
	} catch {
		return emptyVersionCache();
	}
}

/** Writes versions.yaml. */
export async function writeVersionCache(path: string, cache: VersionCache): Promise<void> {
	cache.updated_at = new Date().toISOString();
	await writeText(path, `# Generated by src/main.ts — do not edit by hand.\n${stringify(cache, { lineWidth: 0 })}`);
}
